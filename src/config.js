const KST = 9 * 3600e3;
const kstMidnight = ymd => Date.parse(ymd + 'T00:00:00Z') - KST;   // 한국 0시의 UTC ms
export function priceNow(now = Date.now()) {
  let cur = PRICE_STEPS[0], next = null;
  for (let i = 0; i < PRICE_STEPS.length; i++) {
    if (kstMidnight(PRICE_STEPS[i].from) <= now) cur = PRICE_STEPS[i];
    else { next = PRICE_STEPS[i]; break; }
  }
  return { ...cur, next: next ? { ...next, at: kstMidnight(next.from) } : null, listPrice: BOOK.listPrice,
    off: Math.round((1 - cur.price / BOOK.listPrice) * 100) };
}

